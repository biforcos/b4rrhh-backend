-- backend#158, paso 3 del camino 5 (workspace#20, ADR-077, ADR-078 §3): COUNTRY sube a INT.
--
-- Un pais es el mismo en ESP, FRA y PRT, y la V16 lo sembraba tres veces, una por reglamentacion:
-- diez paises, nombre en ingles y traduccion al castellano (V114). Aqui las tres
-- copias se quedan en una fila en INT (rulesystem.raise_rule_entity_type, V167, que falla si no son
-- identicas), y el catalogo pasa a ser el entero: los 249 codigos de ISO 3166-1, que es la semilla
-- que el camino 4 (workspace#19) necesita para el pais de la direccion.
--
-- Fuente: iso-codes 4.18.0 (Debian, https://salsa.debian.org/iso-codes-team/iso-codes),
-- data/iso_3166-1.json para el codigo alfa-3 y el nombre, e iso_3166-1/es.po para el castellano.
-- Licencia LGPL-2.1-or-later; los datos se reproducen tal cual, sin retocar ninguna traduccion
-- (tambien la tilde de «Costa de Marfíl», que es de la fuente). El nombre de la fila es el de
-- iso-codes en ingles y el castellano va en rule_entity_translation (es-ES), como estaban los
-- diez: los diez coinciden letra a letra con la fuente en los dos idiomas, y por eso no se tocan.
--
-- Codigo alfa-3 y no alfa-2 porque es el que ya guardan employee.address.country_code y
-- employee.identifier.issuing_country_code.

select rulesystem.raise_rule_entity_type('COUNTRY', 'INT');

