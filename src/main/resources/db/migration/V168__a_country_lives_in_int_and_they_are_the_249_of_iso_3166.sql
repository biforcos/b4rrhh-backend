-- Los diez que ya estaban, iguales a la fuente: si no lo fueran, el catalogo tendria dos verdades.
do $$
declare
    differing text;
begin
    select string_agg(format('%s: %s / %s frente a %s / %s', re.code, re.name, tr.name, iso.name, iso.name_es), '; ')
      into differing
      from rulesystem.rule_entity re
      join iso_3166_1 iso on iso.code = re.code
      left join rulesystem.rule_entity_translation tr on tr.rule_entity_id = re.id and tr.language_code = 'es-ES'
     where re.layer_code = 'INT' and re.rule_entity_type_code = 'COUNTRY'
       and (re.name <> iso.name or tr.name is distinct from iso.name_es);
    if differing is not null then
        raise exception 'Los paises sembrados no son los de iso-codes: %', differing using errcode = '23514';
    end if;
end;
$$;

insert into rulesystem.rule_entity (layer_code, rule_entity_type_code, code, name, description, active, start_date)
select 'INT', 'COUNTRY', iso.code, iso.name, 'Country catalog based on ISO 3166-1 alpha-3', true, date '1900-01-01'
  from iso_3166_1 iso
 where not exists (select 1 from rulesystem.rule_entity re
                    where re.layer_code = 'INT' and re.rule_entity_type_code = 'COUNTRY' and re.code = iso.code);

insert into rulesystem.rule_entity_translation (rule_entity_id, language_code, name, description)
select re.id, 'es-ES', iso.name_es, 'Catálogo de países según ISO 3166-1 alfa-3'
  from iso_3166_1 iso
  join rulesystem.rule_entity re on re.layer_code = 'INT' and re.rule_entity_type_code = 'COUNTRY' and re.code = iso.code
 where not exists (select 1 from rulesystem.rule_entity_translation tr
                    where tr.rule_entity_id = re.id and tr.language_code = 'es-ES');
